class Color:
    """
    A collection of predefined color constants for the game.

    This class provides easy access to commonly used RGB color tuples
    throughout the application. All colors are defined as RGB tuples
    with values ranging from 0 to 255.
    """

    # Primary colors
    RED = (255, 0, 0)
    GREEN = (0, 255, 0)
    BLUE = (0, 0, 255)

    # Secondary colors
    YELLOW = (255, 255, 0)
    PURPLE = (128, 0, 128)
    ORANGE = (255, 165, 0)
    TURQUOISE = (64, 224, 208)

    # Neutral colors
    WHITE = (255, 255, 255)
    BLACK = (0, 0, 0)
    GREY = (128, 128, 128)
